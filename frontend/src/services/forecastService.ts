// AirCare Machine-Learning Forecasting Data Service
// Connects UI to Supabase aqi_predictions table and falls back to static forecast cache.

import { getSupabaseClient, isSupabaseConfigured } from './supabaseClient';
import type { CityForecastData, ModelBenchmarkSummary } from '../types';

export interface ForecastResponsePayload {
  metadata: {
    pipeline: string;
    model_name: string;
    model_version: string;
    generated_at: string;
    supported_cities: string[];
    horizons: string[];
    status: string;
    city_count: number;
  };
  forecasts: Record<string, CityForecastData>;
}

export interface ModelEvaluationsPayload {
  timestamp: string;
  evaluation_period: string;
  evaluation_cities: string[];
  horizon_summaries: Record<string, Record<string, ModelBenchmarkSummary>>;
  pollutant_benchmarks: Record<string, Record<string, ModelBenchmarkSummary>>;
}

let cachedForecastPayload: ForecastResponsePayload | null = null;
let cachedEvaluationsPayload: ModelEvaluationsPayload | null = null;

export async function fetchAllForecasts(): Promise<ForecastResponsePayload> {
  if (cachedForecastPayload) {
    return cachedForecastPayload;
  }

  // 1. Try fetching from public/data/forecasts.json
  try {
    const res = await fetch('/data/forecasts.json');
    if (res.ok) {
      const data: ForecastResponsePayload = await res.json();
      cachedForecastPayload = data;
      return data;
    }
  } catch (err) {
    console.warn('[ForecastService] Could not load /data/forecasts.json:', err);
  }

  // 2. Try Supabase aqi_predictions if JSON not found
  if (isSupabaseConfigured()) {
    const supabase = getSupabaseClient();
    if (supabase) {
      try {
        const { data, error } = await supabase
          .from('aqi_predictions')
          .select('*')
          .order('generated_at', { ascending: false })
          .limit(100);

        if (!error && data && data.length > 0) {
          console.info(`[ForecastService] Loaded ${data.length} predictions from Supabase`);
        }
      } catch (sbErr) {
        console.warn('[ForecastService] Supabase fallback query failed:', sbErr);
      }
    }
  }

  throw new Error('Forecast data is currently unavailable. Please generate forecasts using the pipeline.');
}

export async function fetchModelEvaluations(): Promise<ModelEvaluationsPayload | null> {
  if (cachedEvaluationsPayload) {
    return cachedEvaluationsPayload;
  }

  try {
    const res = await fetch('/data/model_evaluations.json');
    if (res.ok) {
      const data: ModelEvaluationsPayload = await res.json();
      cachedEvaluationsPayload = data;
      return data;
    }
  } catch (err) {
    console.warn('[ForecastService] Could not load model evaluations JSON:', err);
  }

  return null;
}

